def main() -> None:
    rows = []
    for pid, name, form, units, daily, price, cat, kids, comp, copy in P:
        rows.append(
            {
                "id": pid,
                "name": name,
                "form": form,
                "units_per_pack": units,
                "daily_units": daily,
                "price_eur": price,
                "category": cat,
                "for_children": kids,
                "per_daily_dose": {k: v for k, v in comp.items() if v},
                "marketing": copy,
            }
        )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        yaml.safe_dump(
            {"note": "Invented catalogue; no real shop's products.", "products": rows},
            sort_keys=False,
            allow_unicode=True,
            width=120,
        )
    )
    print(f"{OUT.name}: {len(rows)} products")


if __name__ == "__main__":
    main()
